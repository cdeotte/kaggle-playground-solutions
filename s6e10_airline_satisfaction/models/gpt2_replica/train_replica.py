#!/usr/bin/env python
"""GReaT replica: GPT-2 fine-tuned as a GReaT model on the ORIGINAL data only (data.csv, 129,880 rows).

The competition data was generated by a GReaT model: a GPT-2 fine-tuned on data.csv, then sampled with a label-first prompt.
These replicas are the starting point of all our GPT classifiers (../gpt2_target_first, ../gpt2_label_anywhere,
../gpt_neo_target_first):
  small : gpt2,                    60 epochs
  medium: gpt2-medium,             60 epochs
  large : gpt2-large,              30 epochs
  neo   : EleutherAI/gpt-neo-125M, 60 epochs
be-great 0.0.3 + transformers 4.26.1 (see requirements.txt) with be-great's default Trainer path (seed 42): batch 16, a random
field order per row, linear learning-rate decay from 5e-5 that ends at the last epoch, AdamW (torch implementation), TF32.
train.csv and test.csv are never read.
Writes checkpoints/<size>/model.pt (+ config.json).
Usage: python train_replica.py --size small|medium|large|neo"""
import argparse
import os
import random
import sys
from pathlib import Path

import numpy as np

np.float = float  # be-great 0.0.3 uses the removed numpy alias

import torch  # noqa: E402
from be_great import GReaT  # noqa: E402
from be_great.great_dataset import GReaTDataset  # noqa: E402
from transformers import set_seed  # noqa: E402

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1]))
from common.data import TARGET, labels, read_original  # noqa: E402

SIZES = {'small': ('gpt2', 60), 'medium': ('gpt2-medium', 60), 'large': ('gpt2-large', 30), 'neo': ('EleutherAI/gpt-neo-125M', 60)}


def batch_getitems(self, keys):
    """Tokenize a batch at once, with the same row order and random.shuffle calls as be-great's per-row path (same tokens)."""
    texts = []
    for key in keys:
        row = self._data.fast_slice(key, 1)
        idx = list(range(row.num_columns))
        random.shuffle(idx)
        texts.append(', '.join('%s is %s' % (row.column_names[i], str(row.columns[i].to_pylist()[0]).strip()) for i in idx))
    enc = self.tokenizer(texts, padding=False)
    return [{field: values[p] for field, values in enc.items()} for p in range(len(keys))]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--size', required=True, choices=list(SIZES))
    a = ap.parse_args()
    llm, epochs = SIZES[a.size]
    out = HERE / 'checkpoints' / a.size
    os.environ.setdefault('TOKENIZERS_PARALLELISM', 'false')
    random.seed(42)
    np.random.seed(42)
    torch.manual_seed(42)
    torch.cuda.manual_seed_all(42)
    set_seed(42)
    GReaTDataset.__getitems__ = batch_getitems
    torch.backends.cuda.matmul.allow_tf32 = True
    torch.backends.cudnn.allow_tf32 = True

    data = read_original()
    data[TARGET] = labels(data[TARGET]).astype(bool)                       # GReaT writes 'satisfaction is True/False'
    data = data[[c for c in data.columns if c != TARGET] + [TARGET]]       # label last
    model = GReaT(llm=llm, experiment_dir=str(out / 'trainer'), epochs=epochs, batch_size=16, logging_strategy='epoch',
                  save_strategy='no', disable_tqdm=True, report_to=[], optim='adamw_torch')
    model.fit(data, conditional_col=TARGET)
    model.save(str(out))
    print(f'saved {out}/model.pt', flush=True)


if __name__ == '__main__':
    main()
