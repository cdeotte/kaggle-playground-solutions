"""GPT-2 BPE pieces of the income values (label-free).

The competition data was generated by a GReaT model (GPT-2), which wrote every income as text, e.g. " 92887.0", and that
string is split into BPE pieces such as [" 9", "28", "87", ".", "0"]. The first piece (the "leading piece") groups incomes
the way the generator saw them: the 10,000 bin for incomes spelled [1][2][2] or [2][2][2], an aligned 1,000 bin for incomes
spelled [2][3], [3][3] or [3][1][2], and so on. Several models use target encodings of the leading piece (and of the first
two pieces) as features.
Usage: table = income_bpe_table(values) -> DataFrame indexed by income with columns pieces, p1, p1p2, n_pieces."""
import numpy as np
import pandas as pd


def tokenizer():
    from transformers import GPT2TokenizerFast
    return GPT2TokenizerFast.from_pretrained('gpt2')


def pieces(income, tok):
    """BPE pieces of one income as GReaT spelled it: a leading space and str(float)."""
    ids = tok.encode(' ' + str(float(income)))
    return [tok.decode([i]) for i in ids]


def income_bpe_table(values, tok=None):
    """One row per distinct income value (NaN skipped)."""
    tok = tok or tokenizer()
    uniq = np.unique(np.asarray(values, np.float64)[~np.isnan(np.asarray(values, np.float64))])
    rows = []
    for v in uniq:
        p = pieces(v, tok)
        rows.append(dict(income=v, pieces=p, p1=p[0].strip(), p1p2=(p[0] + p[1]).strip() if len(p) > 1 else p[0].strip(),
                         n_pieces=len(p)))
    return pd.DataFrame(rows).set_index('income')


def leading_piece(values, table):
    """Map an array of incomes to their leading BPE piece (NaN -> 'nan')."""
    m = table['p1'].to_dict()
    return np.array([m.get(float(v), 'nan') if not np.isnan(v) else 'nan' for v in np.asarray(values, np.float64)], dtype=object)
