"""Table rows as GReaT text and the GReaT replicas, for the GPT-2 models.

The competition data was generated by a GReaT model (a GPT-2 fine-tuned on the original data with be-great 0.0.3), sampled target
first: "Will_Buy_EV is Yes," or "Will_Buy_EV is No," followed by the 13 "<column> is <value>" fields joined by ", " in an order the
model picked itself. Values are str() of the stored value (ints '36', floats '44906.0').
Replicas (models/gpt2_replica/checkpoints/<name>.pt, GPT-2 small state dicts): e55, e60, e65, e70 (legacy recipe; the name is the
length of the training schedule in epochs) and d60 (organizer-default training RNG path, 60 epochs)."""
import random
from pathlib import Path

import numpy as np
import pandas as pd
import torch
from scipy.special import expit

from common.data import DATA_DIR, ROOT
from common.pairs import have_part, save_pair

REPLICA_DIR = ROOT / 'models' / 'gpt2_replica' / 'checkpoints'
SOURCE_ORDER = ['Age', 'Gender', 'Annual_Income_USD', 'City_Type', 'Daily_Commute_km', 'Number_of_Cars_Owned', 'Current_Car_Type',
                'Charging_Stations_Near_Home', 'Charging_Stations_Near_Work', 'Home_Charging_Possible', 'Environmental_Concern_Level',
                'Subsidy_Available', 'Range_Anxiety_Level']   # original dataset column order (Buyer_ID and the target dropped)


def read_frame():
    """train rows then test rows, the 13 predictors in test.csv column order, pandas default dtypes (.astype(str) gives '44906.0',
    '36'). The target is not read. Returns (frame, n_train)."""
    test = pd.read_csv(DATA_DIR / 'test.csv')
    cols = [c for c in test.columns if c != 'id']
    train = pd.read_csv(DATA_DIR / 'train.csv', usecols=['id', *cols])[cols]
    return pd.concat([train, test[cols]], ignore_index=True), len(train)


def read_frame_text():
    """Same rows and columns as read_frame, every value as its exact text in the csv files. Returns (frame, n_train)."""
    train = pd.read_csv(DATA_DIR / 'train.csv', dtype=str, keep_default_na=False)
    test = pd.read_csv(DATA_DIR / 'test.csv', dtype=str, keep_default_na=False)
    cols = [c for c in test.columns if c != 'id']
    return pd.concat([train[cols], test[cols]], ignore_index=True), len(train)


def load_tokenizer():
    from transformers import AutoTokenizer
    tok = AutoTokenizer.from_pretrained('gpt2')
    tok.pad_token = tok.eos_token
    return tok


def load_replica(name, from_config=False):
    """GPT2LMHeadModel (on the CPU) with the weights of replica `name`. The model is built from the pretrained gpt2 weights, or from
    the gpt2 config only (from_config=True); every weight is then overwritten by the replica. State dicts saved by transformers 4.26
    carry attention-mask buffers that newer versions do not have; they are ignored."""
    from transformers import AutoModelForCausalLM, GPT2Config, GPT2LMHeadModel
    model = GPT2LMHeadModel(GPT2Config.from_pretrained('gpt2')) if from_config else AutoModelForCausalLM.from_pretrained('gpt2')
    state = torch.load(REPLICA_DIR / f'{name}.pt', map_location='cpu', weights_only=True)
    res = model.load_state_dict(state, strict=False)
    assert not [k for k in res.missing_keys if k != 'lm_head.weight'], res.missing_keys
    assert not [k for k in res.unexpected_keys if not k.endswith(('attn.bias', 'attn.masked_bias'))], res.unexpected_keys
    model.tie_weights()
    return model


def seed_everything(seed):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)


def order_bank(columns, count, seed):
    """Field orders as indices into `columns`: [columns' own order, original order, then distinct random permutations] (count total)."""
    lookup = {c: i for i, c in enumerate(columns)}
    orders = [list(range(len(columns))), [lookup[c] for c in SOURCE_ORDER]]
    rng = np.random.default_rng(seed)
    seen = {tuple(o) for o in orders}
    while len(orders) < count:
        o = rng.permutation(len(columns)).tolist()
        if tuple(o) not in seen:
            seen.add(tuple(o))
            orders.append(o)
    return orders


def random_orders(spec):
    """'rand<K>[:<seed>]' -> K random permutations of SOURCE_ORDER (column names) from np.random.default_rng(seed), default seed 2025."""
    assert spec.startswith('rand'), spec
    k, _, seed = spec[4:].partition(':')
    rng = np.random.default_rng(int(seed) if seed else 2025)
    return [rng.permutation(SOURCE_ORDER).tolist() for _ in range(int(k))]


def fold_parts(model_dir, name, k):
    """(valid, test) arrays saved by common.pairs.save_part for fold k, as float64."""
    d = Path(model_dir) / 'parts'
    return (np.load(d / f'{name}_f{k}_valid.npy').astype(np.float64), np.load(d / f'{name}_f{k}_test.npy').astype(np.float64))


def assemble_pair(model_dir, name, folds, y=None, sigmoid=False, clip=None):
    """common.pairs.assemble with a final transform, once all 5 folds are done.
    sigmoid=True: the parts hold logits / LLRs; OOF = sigmoid(raw), test = sigmoid(mean of the 5 fold raws) (raw clipped to +-clip).
    sigmoid=False: the parts hold probabilities; OOF and test (mean of the 5 fold probabilities) are clipped to [clip, 1 - clip]."""
    if not all(have_part(model_dir, name, k) for k in range(5)):
        print(f'{name}: not all folds are done yet', flush=True)
        return None
    oof, test = np.zeros(len(folds)), 0.0
    for k in range(5):
        v, t = fold_parts(model_dir, name, k)
        oof[folds == k] = v
        test = test + t / 5
    if sigmoid:
        oof, test = (expit(np.clip(z, -clip, clip)) if clip else expit(z) for z in (oof, test))
    elif clip:
        oof, test = np.clip(oof, clip, 1 - clip), np.clip(test, clip, 1 - clip)
    save_pair(model_dir, name, oof, test)
    if y is not None:
        from sklearn.metrics import roc_auc_score
        print(f'{name}: OOF AUC {roc_auc_score(y, oof):.6f}', flush=True)
    return oof
